# Registry of STL RTL implementations: module_name -> RTL content
_STL_RTL_REGISTRY: dict[str, str] = {}


def _generate_firrtl_reg_rtl(width: int) -> str:
    """Generate RTL for FIRRTLReg external module.

    Port names match ECMT2 STLLibrary::createRegModule:
    - clk, rst: clock and reset
    - read_ready: ready output for read value (always 1)
    - read_data: read output data
    - write_enable: enable input for write method
    - write_ready: ready output for write method (always 1)
    - write_data: write input data

    The register updates when write_enable is high.
    """
    return f"""\
// FIRRTLReg_{width}: Register with read/write interface
// Generated by pycmt2.stl
//
// Matches ECMT2 STLLibrary::createRegModule port naming.

module FIRRTLReg_{width} (
    input  logic               clk,
    input  logic               rst,
    // read value method
    output logic               read_ready,
    output logic [{width-1}:0] read_data,
    // write action method
    input  logic               write_enable,
    output logic               write_ready,
    input  logic [{width-1}:0] write_data
);
    logic [{width-1}:0] value;

    // Read is always ready
    assign read_ready = 1'b1;
    assign read_data = value;

    // Write is always ready
    assign write_ready = 1'b1;

    // Register update on write_enable
    always_ff @(posedge clk) begin
        if (rst) begin
            value <= {width}'h0;
        end else if (write_enable) begin
            value <= write_data;
        end
    end

endmodule
"""


def _generate_wire_rtl(width: int) -> str:
    """Generate RTL for Wire external module.

    Port names match ECMT2 STLLibrary::createWireModule:
    - clk, rst: clock and reset
    - read_ready: ready output for read value (always 1)
    - read_data: read output data
    - write_enable: enable input for write method
    - write_ready: ready output for write method (always 1)
    - write_data: write input data

    Wire updates when write_enable is high (like register but for combinational use).
    """
    return f"""\
// Wire_{width}: Wire with read/write interface
// Generated by pycmt2.stl
//
// Matches ECMT2 STLLibrary::createWireModule port naming.

module Wire_{width} (
    input  logic               clk,
    input  logic               rst,
    // read value method
    output logic               read_ready,
    output logic [{width-1}:0] read_data,
    // write action method
    input  logic               write_enable,
    output logic               write_ready,
    input  logic [{width-1}:0] write_data
);
    logic [{width-1}:0] value;

    // Read is always ready
    assign read_ready = 1'b1;
    assign read_data = value;

    // Write is always ready
    assign write_ready = 1'b1;

    // Wire update on write_enable
    always_ff @(posedge clk) begin
        if (rst) begin
            value <= {width}'h0;
        end else if (write_enable) begin
            value <= write_data;
        end
    end

endmodule
"""


